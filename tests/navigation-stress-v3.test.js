test('interval bounds cover straight translation and rotation in an open field',()=>{
  const field={bounds:[-10,-10,10,10],solids:[]};
  for (const waypoints of [[[0,0,0],[3,0,0]],[[0,0,350],[0,0,10]]]) {
    const r=intervalBounds({waypoints},{length_in:2,width_in:2},field,sampling);
    assert.equal(r.positive_bound_for_all_intervals,true);assert.ok(r.min_clearance_lower_bound_in>0);
    assert.equal(r.first_unresolved_interval,null);
  }
});
test('interval bound refuses sampled-clear motion through an unsampled thin solid',()=>{
  const field={bounds:[-5,-5,5,5],solids:[{id:'thin',vertices_in:[[0.09,-1],[0.11,-1],[0.11,1],[0.09,1]]}]};
  const route={waypoints:[[0,0,0],[0.25,0,0]]},robot={length_in:0.02,width_in:0.02};
  assert.equal(checkRoute(route,robot,field,sampling).collision_free,true);
  const r=intervalBounds(route,robot,field,sampling);
  assert.equal(r.positive_bound_for_all_intervals,false);assert.equal(r.unresolved_intervals,1);
  assert.ok(r.min_clearance_lower_bound_in<0);
  assert.deepEqual(r.first_unresolved_interval.endpoint_hits,[[],[]]);
});
test('contact and intermediate spin collisions cannot receive positive bounds',()=>{
  const field={bounds:[0,0,10,10],solids:[]},robot={length_in:2,width_in:2};
  assert.equal(intervalBounds({waypoints:[[1,1,0],[1,1,90]]},robot,field,sampling).positive_bound_for_all_intervals,false);
  assert.throws(()=>intervalBounds({waypoints:[[0,0,0]]},robot,field,sampling),/two waypoints/);
});
test('coarse rotation cannot conceal corner sweep behind clear endpoints',()=>{
  const field={bounds:[-5,-5,5,5],solids:[{id:'spin-probe',vertices_in:[[1.8,-0.05],[1.9,-0.05],[1.9,0.05],[1.8,0.05]]}]};
  const route={waypoints:[[0,0,-45],[0,0,45]]},robot={length_in:4,width_in:0.2};
  const coarse={translation_step_in:1,rotation_step_deg:90};
  assert.equal(checkRoute(route,robot,field,coarse).collision_free,true);
  assert.equal(checkRoute(route,robot,field,sampling).collision_free,false);
  assert.equal(intervalBounds(route,robot,field,coarse).positive_bound_for_all_intervals,false);
});
test('stress cases preserve inputs, baseline success, blocker failures and per-route diagnostics',()=>{
  const before=JSON.stringify([model,nav,drive,config]);
  // Full matrix is generated by the CLI; select representative rows for suite speed.
  const subset={...config,envelopes:config.envelopes.slice(0,1),obstacle_cases:config.obstacle_cases.filter(c=>c.id!=='off-route-control')};
  const r=runStress(model,nav,drive,subset);
  assert.equal(JSON.stringify([model,nav,drive,config]),before);assert.equal(r.results.length,3);
  const empty=r.results[0];assert.ok(empty.scenarios.every(s=>s.nominal.collision_free&&s.sweep.failures===0));
  assert.ok(empty.scenarios.every(s=>s.nominal_interval_bounds.positive_bound_for_all_intervals));
  for (const blocked of r.results.slice(1)) {
    assert.ok(blocked.scenarios.every(s=>!s.nominal.collision_free&&s.sweep.failures===s.sweep.cases));
    assert.ok(blocked.scenarios.every(s=>s.nominal.first_collision.hits.some(h=>h.includes('blocker'))));
    assert.ok(blocked.scenarios.every(s=>!s.nominal_interval_bounds.positive_bound_for_all_intervals));
  }
  assert.match(summary(r),/empty-control/);assert.match(summary(r),/Interval bounds are nominal only/);
});
test('stress validation rejects ambiguous provenance, duplicate cases and invalid polygons',()=>{
  assert.throws(()=>runStress(model,nav,drive,{...config,envelopes:[]}),/nonempty/);
  assert.throws(()=>runStress(model,nav,drive,{...config,envelopes:[config.envelopes[0],config.envelopes[0]]}),/unique safe/);
  const one={...config,envelopes:config.envelopes.slice(0,1),obstacle_cases:[{id:'unknown',evidence:'measured',obstacles:[]}]};
  assert.throws(()=>runStress(model,nav,drive,one),/explicitly hypothetical/);
  one.obstacle_cases[0]={id:'bad',evidence:'hypothetical',obstacles:[{id:'bad',vertices_in:[[0,0],[0,1],[1,0]]}]};
  assert.throws(()=>runStress(model,nav,drive,one),/counterclockwise/);
});
