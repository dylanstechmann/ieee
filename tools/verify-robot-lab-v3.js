#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const Core = require('../robot-lab-v3/core');
const {buildData} = require('./build-robot-lab-v3');
const root = path.resolve(__dirname, '..');
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const manifestPath = path.join(root,'derived/robot-lab-v3/manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath,'utf8'));
for (const [file,expected] of Object.entries(manifest.input_hashes)) assert.equal(hash(path.join(root,file)),expected,`stale input ${file}`);
for (const [file,expected] of Object.entries(manifest.output_hashes)) assert.equal(hash(path.join(root,file)),expected,`changed output ${file}`);
const data = buildData(), expectedData = `/* Generated by tools/build-robot-lab-v3.js. */\nglobalThis.ROBOT_LAB_DATA = ${JSON.stringify(data)};\n`;
assert.equal(fs.readFileSync(path.join(root,'robot-lab-v3/scene-data.js'),'utf8'),expectedData,'generated scene data differs from sources');
const results = {};
for (const id of ['south','north']) {
  const sim = Core.createSimulation(data,id); sim.step(120);
  assert.equal(sim.state.status,'completed'); assert.equal(sim.state.collision,null); assert.equal(sim.state.tire,'blue');
  assert.deepEqual(sim.state.events.map(e => e.type),['reset','exchange','complete']);
  results[id] = {status:sim.state.status,time_s:sim.state.time,commands:sim.commands.length,collision:null};
}
const assembly = Core.assemblyFrame(data.model,32);
assert.equal(assembly.assembledCount,data.model.parts.length);
const html = fs.readFileSync(path.join(root,'share/Robot-Lab-v3.html'),'utf8');
assert.ok(!/<script[^>]+src=/i.test(html)); assert.ok(!/https?:\/\//i.test(html));
const browserPath = path.join(root,'derived/robot-lab-v3/browser-validation.json');
if (fs.existsSync(browserPath)) {
  const browser = JSON.parse(fs.readFileSync(browserPath,'utf8'));
  assert.equal(browser.status,'passed'); assert.equal(browser.javascript_errors,0);
  for (const check of ['play_pause','step_forward_back','assembly_complete','part_inspection','south_route','north_route','fast_forward','deterministic_rewind','pause_freezes_physics','reset']) assert.equal(browser.checks[check],true,`browser check ${check}`);
}
console.log(JSON.stringify({status:'passed',assembly_parts:assembly.assembledCount,routes:results,standalone:'share/Robot-Lab-v3.html',browser_evidence:fs.existsSync(browserPath)},null,2));
