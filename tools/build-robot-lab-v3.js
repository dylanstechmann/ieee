#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {build} = require('./constrained-field-v3');
const {makeField} = require('./navigation-v3');
const {choose} = require('./confirmation-packet-v3');
const Core = require('../robot-lab-v3/core');
const root = path.resolve(__dirname, '..'), lab = path.join(root, 'robot-lab-v3');
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');

function buildData() {
  const model = read('robot-lab-v3/model.json');
  Core.validateModel(model);
  const source = read('constrained-field-v3.json'), trace = read(source.trace_file);
  const fieldModel = build(source, trace), report = read('derived/connected-navigation-v3/report.json');
  const reference = choose(report, 'selectable-original-regions');
  const field = makeField(fieldModel, reference.row.config, reference.row.config.wall_scenarios[0]);
  const routes = {};
  for (const [id, policy, label] of [
    ['south', 'selectable-original-regions', 'South-end approach · conditional'],
    ['north', 'experimental-north-pit-access', 'North-end approach · experimental']
  ]) {
    const {plan} = choose(report, policy);
    const route = {id, label, policy, target_id:plan.route.target_id,
      waypoints:plan.route.waypoints, docking_waypoint_index:plan.route.docking_waypoint_index,
      segment_indices:plan.segment_indices,
      status:'stored-empty-control-route-not-a-legal-or-complete-mission'};
    Core.compileRoute(route);
    routes[id] = route;
  }
  return {
    generated:'2026-10-31', status:'agent-built-concept-lab-not-hardware-or-rules-validation',
    model,
    field:{
      units:'inches', bounds:{min_x:1, max_x:95, min_y:1, max_y:47},
      features:fieldModel.features, solids:field.solids,
      board:{length:96, width:48, thickness:0.719},
      wallScenario:'inside-nominal', obstacleCase:'empty-control'
    },
    routes,
    sources:[
      'robot-lab-v3/model.json', 'constrained-field-v3.json', source.trace_file,
      'derived/connected-navigation-v3/report.json', 'VERIFIED-FACTS.md',
      'confirmation-questions-v3.json'
    ],
    questionPacket:'derived/confirmation-packet-v3/questions-to-organizer.md'
  };
}

function generate() {
  const data = buildData(), dataText = `/* Generated by tools/build-robot-lab-v3.js. */\nglobalThis.ROBOT_LAB_DATA = ${JSON.stringify(data)};\n`;
  fs.writeFileSync(path.join(lab, 'scene-data.js'), dataText);
  const inputs = ['index.html', 'styles.css', 'core.js', 'renderer.js', 'app.js'];
  for (const file of inputs) if (!fs.existsSync(path.join(lab, file))) throw new Error(`missing lab input ${file}`);
  let html = fs.readFileSync(path.join(lab, 'index.html'), 'utf8');
  html = html.replace('<link rel="stylesheet" href="styles.css">', () => `<style>\n${fs.readFileSync(path.join(lab, 'styles.css'), 'utf8')}\n</style>`);
  for (const file of ['scene-data.js', 'core.js', 'renderer.js', 'app.js']) {
    const tag = `<script src="${file}"></script>`;
    if (!html.includes(tag)) throw new Error(`missing bundle placeholder ${tag}`);
    html = html.replace(tag, () => `<script>\n${fs.readFileSync(path.join(lab, file), 'utf8')}\n</script>`);
  }
  const share = path.join(root, 'share/Robot-Lab-v3.html');
  fs.mkdirSync(path.dirname(share), {recursive:true});
  fs.writeFileSync(share, html);
  const out = path.join(root, 'derived/robot-lab-v3');
  fs.mkdirSync(out, {recursive:true});
  const files = ['robot-lab-v3/model.json', 'robot-lab-v3/index.html', 'robot-lab-v3/styles.css',
    'robot-lab-v3/core.js', 'robot-lab-v3/renderer.js', 'robot-lab-v3/app.js',
    'tools/build-robot-lab-v3.js', 'derived/connected-navigation-v3/report.json',
    'constrained-field-v3.json', read('constrained-field-v3.json').trace_file];
  const manifest = {generated:data.generated, status:data.status,
    standalone:'share/Robot-Lab-v3.html',
    input_hashes:Object.fromEntries(files.map(f => [f, hash(path.join(root, f))])),
    output_hashes:{
      'robot-lab-v3/scene-data.js':hash(path.join(lab, 'scene-data.js')),
      'share/Robot-Lab-v3.html':hash(share)
    }};
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return {data, manifest, share};
}

module.exports = {buildData, generate};
if (require.main === module) {
  const {data, share} = generate();
  console.log(`Wrote ${share}`);
  console.log(`${data.model.parts.length} conceptual parts, ${Object.keys(data.routes).length} conditional routes; no external dependencies.`);
}
