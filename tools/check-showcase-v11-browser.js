#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
async function run(){
  const {chromium}=require(process.env.PLAYWRIGHT_PATH||path.join(os.homedir(),'.cache/node-copies/courselab-frontend/node_modules/playwright'));
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||path.join(os.homedir(),'.cache/ms-playwright/chromium_headless_shell-1247/chrome-headless-shell-linux64/chrome-headless-shell'),headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  try{
    const context=await browser.newContext({offline:true,acceptDownloads:true,viewport:{width:1366,height:900}});
    const page=await context.newPage(),errors=[],external=[];
    page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
    await page.goto(`file://${root}/share/Showcase-v12.html`,{waitUntil:'load'});
    await page.waitForFunction(()=>document.body.dataset.studioReady==='true',null,{timeout:60000});
    await page.locator('#studio-v11').scrollIntoViewIfNeeded();
    const initial=await page.evaluate(()=>robotStudioV11.getDiagnostics());
    assert.equal(initial.assets,10);assert.equal(initial.livePhysics,true);assert.equal(initial.mode,'sequence');
    await page.waitForTimeout(300);
    assert.ok((await page.evaluate(()=>robotStudioV11.getDiagnostics())).assembly.time>0);
    await page.waitForFunction(()=>robotStudioV11.getDiagnostics().mode==='live',null,{timeout:45000});
    await page.locator('#v11-mode').selectOption('replay');
    await page.locator('#v11-play').click();await page.waitForTimeout(400);
    assert.ok((await page.evaluate(()=>robotStudioV11.getDiagnostics())).cursor>0);
    await page.locator('#v11-reset').click();
    await page.locator('#v11-scenario').selectOption('1');
    await page.locator('#v11-seek').fill('200');
    assert.equal((await page.evaluate(()=>robotStudioV11.getDiagnostics())).cursor,200);
    await page.locator('#v11-mode').selectOption('assembly');
    await page.locator('#v11-diameter').fill('84');await page.locator('#v11-diameter').dispatchEvent('change');
    const revised=await page.evaluate(()=>robotStudioV11.getDiagnostics());
    assert.equal(revised.stack.axleHeightMm,42);assert.equal(revised.configurationId,'hypothetical-wheel-variant');
    await page.locator('#v11-mode').selectOption('live');
    const editedRun=await page.evaluate(()=>robotStudioV11.getDiagnostics().live);
    assert.equal(editedRun.identity.assemblyId,'hypothetical-wheel-variant');assert.equal(editedRun.parameters.wheelRadius,.042);
    const downloadPromise=page.waitForEvent('download').catch(e=>{throw Error(e.message+' page errors: '+JSON.stringify(errors));});await page.locator('#v11-export-run').evaluate(button=>button.click());
    const download=await downloadPromise;const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(exported.assemblyId,editedRun.identity.assemblyId);assert.equal(exported.state.parameters.wheelRadius,.042);
    await page.locator('#v11-mode').selectOption('live');
    await page.locator('#v11-live-play').click();await page.waitForTimeout(100);await page.locator('#v11-live-play').click();
    const paused=(await page.evaluate(()=>robotStudioV11.getDiagnostics().live)).time;await page.waitForTimeout(150);
    assert.equal((await page.evaluate(()=>robotStudioV11.getDiagnostics().live)).time,paused);
    await page.locator('#v11-arena').selectOption('organizer');
    const organizerInitial=await page.evaluate(()=>robotStudioV11.getDiagnostics().live);
    assert.equal(organizerInitial.arenaId,'organizer');assert.equal(organizerInitial.time,0);
    const organizer=await page.evaluate(()=>robotStudioV11.advanceLive(72000));
    assert.notEqual(organizer.result,'running');assert.ok(organizer.terminalReason);
    await page.locator('#v11-workspace').screenshot({path:path.join(root,'derived/showcase-v12/organizer-live.png')});
    await page.locator('#v11-arena').selectOption('demo');
    await page.locator('#v11-mode').selectOption('assembly');
    await page.locator('#v11-restore').click();
    assert.equal((await page.evaluate(()=>robotStudioV11.getDiagnostics())).stack.axleHeightMm,40);
    const out=path.join(root,'derived/showcase-v12/screenshots');fs.mkdirSync(out,{recursive:true});
    await page.locator('#v11-workspace').screenshot({path:path.join(out,'assembly.png')});
    await page.locator('#v11-mode').selectOption('replay');await page.locator('#v11-seek').fill('200');
    await page.locator('#v11-workspace').screenshot({path:path.join(out,'mission.png')});
    await page.locator('#v11-mode').selectOption('live');
    const live=await page.evaluate(()=>robotStudioV11.advanceLive(72000));
    assert.equal(live.result,'passed');assert.equal(live.laps,3);assert.ok(live.carriedSeconds>20);
    await page.locator('#v11-workspace').screenshot({path:path.join(out,'live-complete.png')});
    await page.locator('#v11-live-scenario').selectOption('missing');
    const missing=await page.evaluate(()=>robotStudioV11.advanceLive(72000));assert.equal(missing.result,'failed');
    await page.setViewportSize({width:390,height:844});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
    assert.equal(overflow,false,'Narrow page must not overflow horizontally');
    assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
    const report={schema:'showcase-v12-browser/1',htmlSha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'share/Showcase-v12.html'))).digest('hex'),browser:await browser.version(),offline:true,protocol:'file:',errors,externalRequests:external,initial,revised,editedRun,exportedRunIdentity:exported.assemblyId,organizer,live,missing,narrowOverflow:overflow,checks:['load','assembly animation','play','reset','bail-out trace','seek','dimension revision','edited run identity and radius','download actual run JSON','pause freezes simulation','organizer arena switch resets world','organizer live terminal attempt','restore','live three-lap contact mission','missing tire fails','narrow layout'],limitations:['no real GPU performance qualification','level-plane chassis and ideal lift; organizer-field attempts do not constitute competition qualification']};
    fs.writeFileSync(path.join(root,'derived/showcase-v12/browser-validation.json'),JSON.stringify(report,null,2)+'\n');
    console.log(JSON.stringify({checks:report.checks.length,errors:errors.length,externalRequests:external.length,screenshots:4,organizer:organizer.result}));
  }finally{await browser.close();}
}
module.exports={run};if(require.main===module)run().catch(e=>{console.error(e);process.exitCode=1;});